# -*- coding: utf-8 -*-
"""演示用示例知识库。

创空间是公开链接，访问者不会自己上传文档；空知识库会让 RAG 演示无从问起。
这里准备三份示例资料，在**每个会话**初始化时写进该会话自己的内存库：
访问者一进来就能直接提问，看到的引用也是真片段。

为什么不再像以前那样在构建镜像时写进共享库：共享库是所有访客共用的，
一个人点「清空知识库」就把演示数据删了；而且那份数据和界面上传的文档
走的是两条不同的入库路径，正是重构前「两套检索」的来源之一。
现在演示数据也走和界面上传完全相同的一条路：chunk_text → encode → add。

开关是 config.DEMO_KB（环境变量 RAG_DEMO_KB=1），默认关闭：
本地开发和测试不需要凭空多出三份文档，只有演示环境打开。
"""
from documents import chunk_text
from embedding import encode

# 三份示例资料：覆盖制度/流程/产品问答，能演示「同义不同词也能召回」
SAMPLES = {
    "员工手册（节选）.txt": (
        "试用期为三个月，试用期工资为转正工资的百分之八十，转正后按岗位薪级核定。"
        "核心工作时间为上午十点至下午四点，其余时间弹性安排，每日工作时长不少于八小时。"
        "公司为员工缴纳五险一金，入职满一年享有五天带薪年假，之后每满一年增加一天，上限十五天。"
        "远程办公每周可申请两天，需提前一天向直属主管报备。"
    ),
    "差旅与报销制度.txt": (
        "出差需提前在系统提交申请，经直属主管与部门负责人两级审批后方可订票。"
        "市内交通凭票据实报销；高铁二等座、经济舱机票可全额报销。"
        "住宿标准为一线城市每晚不超过六百元，其他城市不超过四百元。"
        "报销单需在出差结束后十个工作日内提交，超过三十天不予受理。"
    ),
    "产品常见问题.txt": (
        "本系统支持上传 txt、md、pdf、docx 四种格式的文档建立私有知识库。"
        "检索采用两阶段策略：先用向量召回二十个候选片段，再用精排模型选出最相关的四个。"
        "知识库按客户端标识分目录存储，不同用户之间互不可见，服务重启后数据自动恢复。"
        "所有回答都可以在下方查看命中的原文片段，用于核对答案是否可靠。"
    ),
}


def seed(kb, encoder=encode) -> int:
    """把示例资料写进 kb，返回写入后该库的片段数。

    已有内容时不写入：用户自己的文档不该被示例覆盖。
    encoder 可注入，单测里换成立即返回的假编码器，避免加载真模型。
    """
    if kb.ready:
        return kb.count()

    for source, text in SAMPLES.items():
        chunks = chunk_text(text)
        if not chunks:
            continue
        kb.add(chunks, encoder(chunks), source=source)

    return kb.count()
